import pandas as pd
import joblib

from sklearn.metrics import classification_report, confusion_matrix

print("=" * 60)
print("     NeuroKernel Anomaly-Type Analysis")
print("=" * 60)

# Load model
model = joblib.load("neurokernel_random_forest.pkl")

# Load test data
X_test = pd.read_csv("X_test.csv")
y_test = pd.read_csv("y_test.csv")["label"]

# Load original dataset
df = pd.read_csv("neurokernel_final.csv")

# Recreate the same train/test split indices
from sklearn.model_selection import train_test_split

X = df[
    [
        "cpu_percent",
        "memory_mb",
        "memory_percent",
        "threads",
        "context_switches",
        "cpu_user_time",
        "cpu_system_time",
        "cpu_delta",
        "read_bytes_per_sec",
        "write_bytes_per_sec"
    ]
]

y = df["label"]

_, X_test_original, _, y_test_original = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

# Get corresponding anomaly types
# Use the same indices generated by the split
_, test_indices = train_test_split(
    df.index,
    test_size=0.20,
    random_state=42,
    stratify=y
)

test_types = df.loc[test_indices, "anomaly_type"].reset_index(drop=True)

# Predictions
predictions = model.predict(X_test)

results = pd.DataFrame({
    "actual_label": y_test.reset_index(drop=True),
    "predicted_label": predictions,
    "anomaly_type": test_types
})

print("\nOverall confusion matrix:")
print(confusion_matrix(
    results["actual_label"],
    results["predicted_label"]
))

print("\nPerformance by anomaly type:")

for anomaly_type in results["anomaly_type"].unique():

    subset = results[
        results["anomaly_type"] == anomaly_type
    ]

    print("\n" + "-" * 50)
    print("Type:", anomaly_type)
    print("Samples:", len(subset))

    print(
        classification_report(
            subset["actual_label"],
            subset["predicted_label"],
            labels=[0, 1],
            target_names=["Normal", "Anomaly"],
            zero_division=0
        )
    )

print("\n" + "=" * 60)
print("Analysis completed")
print("=" * 60)

